import { test, expect, type APIRequestContext, type WebSocketRoute } from '@playwright/test';
import { randomUUID } from 'node:crypto';
const API = 'http://localhost:3001';
async function post(request: APIRequestContext, path: string, token: string | undefined, data: unknown) {
  const response = await request.post(API + path, { headers: token ? { Authorization: `Bearer ${token}` } : {}, data });
  expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
}
test('push updates reach a second caregiver; stale modal edits conflict; child and recurring reminder controls work', async ({ browser, request }) => {
  const suffix = Date.now();
  const owner = await post(request, '/auth/register', undefined, { name: 'Owner', email: `live-owner-${suffix}@test.example`, password: 'safe family passphrase' });
  const caregiver = await post(request, '/auth/register', undefined, { name: 'Caregiver', email: `live-care-${suffix}@test.example`, password: 'safe family passphrase' });
  const household = await post(request, '/households', owner.token, { name: 'Realtime nest', timezone: 'America/Chicago' });
  const path = `/households/${household.id}`;
  const child = await post(request, path + '/children', owner.token, { firstName: 'Robin', dateOfBirth: '2026-01-01' });
  const invite = await post(request, path + '/invitations', owner.token, { email: caregiver.user.email, role: 'caregiver' });
  await post(request, '/invitations/accept', caregiver.token, { token: invite.token });
  const event = { id: randomUUID(), childIds: [child.id], category: 'bottle', occurredAt: new Date().toISOString(), details: { quantity: 120, unit: 'ml' }, notes: 'Initial log' };
  await post(request, path + '/sync', owner.token, [{ mutationId: randomUUID(), eventId: event.id, baseVersion: 0, operation: 'create', event }]);
  const a = await browser.newContext(); const b = await browser.newContext();
  await a.addInitScript(auth => sessionStorage.setItem('nestwise.session', JSON.stringify(auth)), owner);
  await b.addInitScript(auth => sessionStorage.setItem('nestwise.session', JSON.stringify(auth)), caregiver);
  const ownerPage = await a.newPage(); const caregiverPage = await b.newPage();
  let downstream: WebSocketRoute; let upstream: WebSocketRoute;
  await caregiverPage.routeWebSocket('ws://localhost:3001/realtime', route => { downstream = route; upstream = route.connectToServer(); });
  const pageErrors: string[] = []; for (const page of [ownerPage, caregiverPage]) page.on('pageerror', e => pageErrors.push(e.message));
  try {
    await ownerPage.goto('/timeline'); await caregiverPage.goto('/timeline');
    await expect(ownerPage.getByText('All up to date', { exact: true })).toBeVisible();
    await expect(caregiverPage.getByText('All up to date', { exact: true })).toBeVisible();
    let snapshots = 0; caregiverPage.on('request', req => { if (req.url().endsWith('/snapshot')) snapshots++; });
    await caregiverPage.getByRole('button', { name: 'Edit log', exact: true }).click();
    await caregiverPage.getByRole('textbox', { name: 'Notes', exact: true }).fill('Caregiver unsynced correction');
    await ownerPage.getByRole('button', { name: 'Edit log', exact: true }).click();
    await ownerPage.getByRole('textbox', { name: 'Notes', exact: true }).fill('Owner live correction');
    await ownerPage.getByRole('button', { name: 'Confirm changes', exact: true }).click();
    await expect(caregiverPage.getByText('Owner live correction', { exact: true })).toBeVisible({ timeout: 4000 });
    await caregiverPage.getByRole('button', { name: 'Confirm changes', exact: true }).click();
    await expect(caregiverPage.getByText(/1 sync conflict/)).toBeVisible();
    await caregiverPage.getByRole('link', { name: 'Settings', exact: true }).click();
    await expect(caregiverPage.getByText(/Caregiver unsynced correction/)).toBeVisible();
    await caregiverPage.getByRole('button', { name: 'Keep server version', exact: true }).click();
    await caregiverPage.getByRole('dialog', { name: 'Keep server version?' }).getByRole('button', { name: 'Keep server version', exact: true }).click();
    await expect(caregiverPage.getByText(/Server reachable · 0 queued logs · 0 conflicts/)).toBeVisible();
    expect(snapshots).toBe(0);
    await caregiverPage.getByRole('link', { name: 'Timeline', exact: true }).click();
    await downstream!.close({ code: 1012, reason: 'Test transport interruption' }); await upstream!.close();
    await post(request, path + '/sync', owner.token, [{ mutationId: randomUUID(), eventId: event.id, baseVersion: 2, operation: 'update', event: { ...event, notes: 'Recorded during disconnection' } }]);
    await expect(caregiverPage.getByText('Recorded during disconnection', { exact: true })).toBeVisible({ timeout: 8000 });
    await expect(caregiverPage.getByText('All up to date', { exact: true })).toBeVisible();
    expect(snapshots).toBe(0);
    await ownerPage.getByRole('link', { name: 'Children', exact: true }).click();
    await ownerPage.getByRole('button', { name: 'Edit Robin', exact: true }).click();
    await ownerPage.getByRole('dialog', { name: 'Edit child' }).getByRole('textbox', { name: 'Nickname', exact: true }).fill('Little bird');
    await ownerPage.getByRole('button', { name: 'Save child changes', exact: true }).click();
    await expect(ownerPage.getByText(/Little bird/)).toBeVisible();
    await ownerPage.getByRole('button', { name: 'Archive Robin', exact: true }).click();
    await ownerPage.getByRole('button', { name: 'Archive child', exact: true }).click();
    await expect(ownerPage.getByRole('heading', { name: 'Robin · Archived', exact: true })).toBeVisible();
    await ownerPage.getByRole('button', { name: 'Restore Robin', exact: true }).click();
    await ownerPage.getByRole('button', { name: 'Restore child', exact: true }).click();
    await ownerPage.getByRole('link', { name: 'Reminders', exact: true }).click();
    await ownerPage.getByRole('textbox', { name: 'Reminder', exact: true }).fill('Recurring care bag');
    await ownerPage.getByRole('checkbox', { name: 'Robin', exact: true }).click();
    await ownerPage.getByRole('radio', { name: 'Every 24 hours', exact: true }).click();
    await ownerPage.getByRole('button', { name: 'Add reminder', exact: true }).click();
    await expect(ownerPage.getByText(/Repeats every 1440 minutes/)).toBeVisible();
    await ownerPage.getByRole('button', { name: 'Snooze 15 minutes', exact: true }).click();
    await ownerPage.getByRole('button', { name: 'Mark complete', exact: true }).click();
    await expect(ownerPage.getByRole('heading', { name: 'Recurring care bag', exact: true })).toHaveCount(1);
    await ownerPage.getByRole('link', { name: 'Settings', exact: true }).click();
    await ownerPage.getByRole('radio', { name: 'dark', exact: true }).click(); await ownerPage.reload();
    await expect(ownerPage.getByRole('radio', { name: 'dark', exact: true })).toHaveAttribute('aria-checked', 'true');
    await ownerPage.screenshot({ path: 'test-results/milestone-desktop-dark.png', fullPage: true });
    await ownerPage.setViewportSize({ width: 390, height: 844 });
    await ownerPage.screenshot({ path: 'test-results/milestone-mobile-dark.png', fullPage: true });
    expect(await ownerPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(pageErrors).toEqual([]);
  } finally { await a.close(); await b.close(); }
});
