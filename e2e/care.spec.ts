import { test, expect } from '@playwright/test';
test('family care journey: registration, siblings, confirmed logging, timer, offline reload, report and mobile layout', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'New to NestWise? Create an account' }).click();
  await page.getByRole('textbox', { name: 'Your name', exact: true }).fill('Test Parent');
  await page.getByRole('textbox', { name: 'Email address' }).fill(`journey-${Date.now()}@example.test`);
  await page.getByRole('textbox', { name: 'Password', exact: true }).fill('a secure family passphrase');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('textbox', { name: 'Household name' }).fill('The Willow Family');
  await page.getByRole('button', { name: 'Create household', exact: true }).click();
  await page.getByRole('button', { name: 'Add a child', exact: true }).click();
  for (const name of ['River', 'Sage']) {
    await page.getByRole('textbox', { name: 'First name', exact: true }).fill(name);
    await page.getByRole('textbox', { name: 'Date of birth', exact: true }).fill('2026-01-01');
    await page.getByRole('button', { name: 'Add child', exact: true }).click();
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  }
  await page.getByRole('link', { name: 'Timeline', exact: true }).click();
  await page.getByRole('button', { name: 'Log care', exact: true }).click();
  await page.getByRole('textbox', { name: 'Quick phrase' }).fill('bottle 120 ml');
  await page.getByRole('button', { name: 'Review phrase', exact: true }).click();
  await expect(page.getByText('Draft ready to review. Nothing has been saved.')).toBeVisible();
  await page.getByRole('checkbox', { name: 'Sage', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm and save', exact: true }).click();
  await expect(page.getByText('Bottle · River & Sage', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Log care', exact: true }).click();
  await page.getByRole('dialog', { name: 'Log a little moment' }).getByRole('radio', { name: 'Sleep', exact: true }).click();
  await page.getByRole('button', { name: 'Save and start timer', exact: true }).click();
  await page.getByRole('button', { name: 'Stop timer', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Stop timer', exact: true })).toHaveCount(0);
  await expect(page.getByText('All up to date', { exact: true })).toBeVisible();
  // Block API traffic while keeping the static app available, then reload to prove durable recovery.
  await page.route('http://localhost:3001/**', route => route.abort('internetdisconnected'));
  await page.getByRole('button', { name: 'Log care', exact: true }).click();
  await page.getByRole('textbox', { name: 'Quick phrase' }).fill('wet diaper');
  await page.getByRole('button', { name: 'Review phrase', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm and save', exact: true }).click();
  await expect(page.getByText('Diaper · River', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('Diaper · River', { exact: true })).toBeVisible();
  await page.unroute('http://localhost:3001/**');
  await page.getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Sync now', exact: true }).click();
  await expect(page.getByText('Server reachable · 0 queued logs · 0 conflicts', { exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Reports', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export care CSV', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('nestwise-care-report.csv');
  await page.getByRole('link', { name: 'Reminders', exact: true }).click();
  await page.getByRole('textbox', { name: 'Reminder', exact: true }).fill('Pack the care bag');
  await page.getByRole('button', { name: 'Add reminder', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pack the care bag', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Mark complete', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Pack the care bag', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.screenshot({ path: 'test-results/desktop-overview.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'More', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/mobile-overview.png', fullPage: true });
  await page.getByRole('button', { name: 'More', exact: true }).click();
  await page.getByRole('dialog', { name: 'Your nest', exact: true }).getByRole('link', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Welcome back', exact: true })).toBeVisible();
  expect(await page.evaluate(() => Object.keys(localStorage).filter(key => key.includes('nestwise.cache.')))).toEqual([]);
  expect(errors).toEqual([]);
});
